"""Отказ по запрещённому содержанию — до списания денег.

Две мысли, которые определили устройство.

Первая: проверять надо ДО обращения к провайдеру. Провайдер такое всё равно
отклонит, но деньги за попытку уже спишутся, а клиент получит невнятную ошибку
вместо объяснения.

Вторая: ложное срабатывание дороже пропуска. Фильтр, режущий купальники и
ню-арт, отнимает деньги у клиента, который ничего не нарушал. Поэтому режем
только то, за что бывают настоящие последствия: сексуализацию детей и явное
порно. Всё пограничное уходит провайдеру — пусть он решает.

Отсюда же приём: детские слова сами по себе безобидны («ребёнок играет во
дворе»), сексуальные сами по себе допустимы («откровенная сцена»). Блокирует
только их сочетание.

Проверка на словах, без обращения к модели: стоит ноль, работает мгновенно и не
делает отказ зависимым от чужого сервиса.

Пример самостоятельный, запускается как есть.
"""

from __future__ import annotations

import re


class BlockedContent(Exception):
    """Запрос выполнять нельзя. Текст исключения уходит клиенту."""


MINORS_MESSAGE = (
    "Такой запрос запрещён: мы не создаём изображения сексуального характера "
    "с участием детей. Запрос не выполнен, кредиты не списаны."
)
EXPLICIT_MESSAGE = (
    "Мы не генерируем откровенный контент 18+. Опишите сцену без явных "
    "сексуальных подробностей — кредиты не списаны."
)

# Латиница вместо кириллицы — самый простой обход списка слов: «пoрно» с
# латинской o для человека выглядит так же, а для регулярки уже другое слово.
_HOMOGLYPHS = str.maketrans({
    "a": "а", "b": "в", "c": "с", "e": "е", "h": "н", "k": "к",
    "m": "м", "o": "о", "p": "р", "t": "т", "x": "х", "y": "у",
})

# Кто на кадре. В обычной речи «девочка» означает взрослую, поэтому одни эти
# слова ничего не блокируют — только вместе с сексуальным контекстом.
_CHILD = (
    r"ребен[кочм]", r"\bдет[иеямьск]", r"малыш", r"малолет", r"школьниц",
    r"школьник", r"девочк", r"мальчик", r"подрост", r"несовершеннолет",
    r"\bchild", r"\bkids?\b", r"toddler", r"\bteens?\b", r"schoolgirl",
)

# Сексуальный контекст. Список намеренно широкий: в одиночку он безопасен.
_SEXUAL = (
    r"голы[йеамх]", r"голая", r"обнажен", r"раздет", r"без одежды",
    r"эротик", r"эротич", r"порн", r"секс", r"интим", r"откровенн",
    r"\bnude\b", r"\bnaked\b", r"\bsex", r"\bporn", r"erotic", r"lingerie",
)

# Прямые обозначения запрещённого — блокируют сами по себе.
_MINORS_DIRECT = (r"\bлоли\b", r"\blolic?on", r"child\s*porn", r"детск\w*\s+порн")

# Явное порно: описания действий, а не «красивая девушка».
_EXPLICIT = (
    r"\bпорно", r"\bporn\b", r"hardcore\s*sex", r"минет", r"оргия",
    r"групповух", r"\bblowjob", r"\bgangbang", r"\banal\s*sex", r"\bxxx\b",
)


def _normalize(text: str) -> str:
    return re.sub(r"[^\w\s]+", " ", (text or "").lower().replace("ё", "е"))


def _hit(patterns: tuple[str, ...], text: str) -> str | None:
    return next((p for p in patterns if re.search(p, text)), None)


def check(prompt: str | None) -> None:
    """Бросает BlockedContent, если запрос выполнять нельзя."""
    if not prompt:
        return
    text = _normalize(prompt)
    # Проверяем оба варианта: как есть и с приведёнными двойниками.
    for variant in (text, text.translate(_HOMOGLYPHS)):
        if _hit(_MINORS_DIRECT, variant):
            raise BlockedContent(MINORS_MESSAGE)
        if _hit(_CHILD, variant) and _hit(_SEXUAL, variant):
            raise BlockedContent(MINORS_MESSAGE)
        if _hit(_EXPLICIT, variant):
            raise BlockedContent(EXPLICIT_MESSAGE)


if __name__ == "__main__":
    cases = [
        "закат над морем",                    # обычный
        "девушка в купальнике у бассейна",    # пограничный, пропускаем намеренно
        "ребенок играет в футбол во дворе",   # ребёнок без пикантности
        "откровенная сцена в спальне",        # взрослый контекст без детей
        "голая девочка 12 лет",               # сочетание — блок
        "пoрно",                              # латинская o — блок
    ]
    for prompt in cases:
        try:
            check(prompt)
            print(f"  пропущено  │ {prompt}")
        except BlockedContent as exc:
            print(f"  ОТКЛОНЕНО  │ {prompt}\n             └─ {exc}")
